#!/usr/bin/env python3
"""Generate Source/JunoFactoryBank.h from a Juno-106 librarian ".106" file.

The .106 file is Java-serialized: a Library holding a Vector of Patch objects,
each with a `name` String and an 18-byte `sysex` array (16 slider positions
plus the two switch bytes of a Roland Juno-106 patch). This extracts those
pairs and writes them as a C++ table; the plugin decodes the bytes with
juno::Juno106Patch::decode.

Usage: python3 -I Tools/import_106_library.py <library.106> <output.h>
"""
import sys

PATCH_BYTES = 18
EXPECTED_PATCHES = 128


def extract_patches(data: bytes):
    patches = []
    i = 0
    while i < len(data) - 3:
        if data[i] == 0x74:  # TC_STRING
            n = int.from_bytes(data[i + 1:i + 3], "big")
            name = data[i + 3:i + 3 + n]
            after = i + 3 + n
            if (0 < n < 64 and all(32 <= b < 127 for b in name)
                    and after < len(data) and data[after] == 0x75):  # TC_ARRAY follows
                j = data.find(PATCH_BYTES.to_bytes(4, "big"), after, after + 40)
                if j != -1:
                    payload = data[j + 4:j + 4 + PATCH_BYTES]
                    patches.append((name.decode("ascii"), payload))
                    i = j + 4 + PATCH_BYTES
                    continue
        i += 1
    return patches


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)

    src, out = sys.argv[1], sys.argv[2]
    patches = extract_patches(open(src, "rb").read())

    if len(patches) != EXPECTED_PATCHES:
        sys.exit(f"expected {EXPECTED_PATCHES} patches, found {len(patches)}")
    for name, payload in patches:
        if len(payload) != PATCH_BYTES or any(b & 0x80 for b in payload):
            sys.exit(f"patch {name!r} is not {PATCH_BYTES} 7-bit bytes")
    if len({n for n, _ in patches}) != len(patches):
        sys.exit("duplicate patch names")

    lines = [
        "#pragma once",
        "",
        "// Generated by Tools/import_106_library.py from the Juno-106 factory library",
        "// (Java librarian .106 file). Do not edit by hand; re-run the tool instead.",
        "",
        "namespace juno",
        "{",
        "",
        "struct FactoryPatchData",
        "{",
        "    const char* name;",
        "    unsigned char data[18];   // 16 sliders + 2 switch bytes, as in Juno-106 SysEx",
        "};",
        "",
        "inline constexpr FactoryPatchData factoryBank[] =",
        "{",
    ]
    for name, payload in patches:
        hexes = ", ".join(f"0x{b:02x}" for b in payload)
        lines.append(f"    {{ {c_string(name)}, {{ {hexes} }} }},")
    lines += [
        "};",
        "",
        "inline constexpr int numFactoryPatches = (int) (sizeof (factoryBank) / sizeof (factoryBank[0]));",
        "",
        "} // namespace juno",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(patches)} patches to {out}")


if __name__ == "__main__":
    main()
